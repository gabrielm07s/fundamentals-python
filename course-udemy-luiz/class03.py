"""
Tipo de Dado String
String são textos que estã dentro de aspas (simples ou duplas)
"""
print("Hello, world!")
print('Hello, world!')

# Caractere de escape
# Você "escapa" um caractere especial
print("Luiz \"Otávio\"")

# r
# Podemos usar o r para mostrar o caractere de escape e pode ser usado para expressões regulares também
print(r"Luiz \"Otávio\"")

# Método mais simples
print("Luiz 'Otávio'")
print('Luiz "Otávio"')
