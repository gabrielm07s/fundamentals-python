"""
Operadores Aritméticos

Adição: +
Subtração: -
Multiplicação: *
Divisão: /
Divisão Inteira: //
Exponenciação: **
Módulo: %
"""
adicao = 10 + 10
print('Adição', adicao)

subtracao = 10 -5
print('Subtração', subtracao)

multiplicacao = 10 * 10
print('Multiplicação', multiplicacao)

divisao = 10 / 2.2 # sempre retorna float
print('Divisão', divisao)

divisao_inteira = 10 // 2.2
print('Divisão Inteira', divisao_inteira)

exponenciacao = 10 ** 2
print('Exponenciação', exponenciacao)

modulo = 10 % 3 # resto da divisão
print('Módulo', modulo)

print(10 % 8 == 0)
print(16 % 8 == 0)
print(10 % 2 == 0)
print(15 % 3 == 0)