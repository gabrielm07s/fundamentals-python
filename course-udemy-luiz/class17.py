"""
Operadores Relacionais (de comparação)

> maior que
>= maior ou igual a
< menor que
<= menor ou igual a
== igual a
!= diferente de
"""
maior = 2 > 1
maior_ou_igual = 2 >= 2 
menor = 1 < 2
menor_ou_igual = 2 <= 2 
igual =  'a' == 'a'
diferente = 'a' != 'b'

print(maior)
print(maior_ou_igual)
print(menor)
print(menor_ou_igual)
print(igual)
print(diferente)
