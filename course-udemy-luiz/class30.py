"""
Operadores de Atribuição

+= soma na mesma variável
-= subtração na mesma variável
*= multiplicação na mesma variável
**= exponenciação na mesma variável
/= divisão na mesma variável
//= divisão inteira na mesma variável
%= módulo na mesma variável
"""
contador = 10

contador += 1
print(contador)

contador -= 1
print(contador)

contador *= 10
print(contador)

contador /= 10
print(contador)

contador //= 5
print(contador)

contador %= 5
print(contador)

contador **= 2
print(contador)