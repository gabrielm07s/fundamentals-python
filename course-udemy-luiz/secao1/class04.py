"""
Tipos int e float
int -> Números inteiros, sem ponto flutuante
O tipo int representa qualquer número positivo ou negativo, int sem sinal é considerado positivo
"""
print(11) 
print(-11) 
print(0)

"""
float -> Números com ponto flutuante
O tipo float representa qualquer número positivo ou negativo com ponto flutuante
O tipo float sem sinal e considerado positivo
"""
print(1.1) 
print(1.1, 10.11)
print(0.0) 
print(-1.5)

"""
A função type() mostra o tipo que o Python inferiu o valor
"""
print(type(11))
print(type(-11.90))
print(type('Otávio'))