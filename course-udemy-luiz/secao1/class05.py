"""
Tipo de dado bool (boolean)
O tipo booleano só permite duas respostas possíveis:
True (sim) ou False (não)

Existem operadores para "questionar" como o "==" 
"==" é um operador lógico de igualdade que questiona se um valor é igual a outro
"""
print(10 == 10) # True (verdadeiro)
print(10 == 11) # False (falso)
print(type(10 == 10)) 
print(type(10 == 11)) 