"""
Fatiamento de strings

[i:f:p] [::]

OBS! a função len retorna a quantidade de caracteres da string
"""
variavel = 'Olá mundo'
print(variavel[5])
print(variavel[-4])

print(variavel[4:7])
print(variavel[:7])
print(variavel[::]) # exibe tudo)
print(variavel[::2])
print(variavel[::3])

# função len
print(len(variavel))

