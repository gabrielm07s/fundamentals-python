"""
Crie uma tupla com os dias da semana ('Domingo' a 'Sábado') e imprima: a tupla inteira, o primeiro dia, 
o último dia, o tamanho da tupla (len) e o tipo da variável (type).
"""
dias_semana = ('Domingo', 'Segunda', 'Terça', 'Quarta', 'Quinta', 'Sexta', 'Sábado')

print(f'Dias da semana: {dias_semana}')
print(f'Primeiro dia: {dias_semana[0]}')
print(f'último dia: {dias_semana[-1]}')
print(f'Tamanho da tupla: {len(dias_semana)}')
print(f'Tipo da variável: {type(dias_semana)}')