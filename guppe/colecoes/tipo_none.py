"""
Tipo None

O tipo de dado None em Python representa o tipo sem tipo, ou poderia ser conhecido também como tipo vazio,
porém o apropriado é um tipo sem tipo

O certo é com o N maiúsculo -> None

Podemos utilizar None quando queremos criar uma variável e inicializá-la com um tipo sem tipo, antes de recebermos
um valor final

O tipo None sempre é considerado False
"""
numeros = None
print(numeros, type(numeros))

numeros = 1.44, 1.34, 5.67
print(numeros, type(numeros))